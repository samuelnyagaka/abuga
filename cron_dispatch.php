<?php
/**
 * Cron Task Dispatcher
 * Tailor Business Management & Marketing System
 * 
 * Specifically designed for InfinityFree Free Tier:
 * Since InfinityFree has no native cron daemon, point a free external service
 * (such as cron-job.org or uptimerobot) to this URL every 24 hours:
 * https://yourdomain.com/cron_dispatch.php?token=YOUR_CRON_TOKEN
 */

header('Content-Type: application/json; charset=utf-8');

require_once __DIR__ . '/config/app.php';
require_once __DIR__ . '/includes/db.php';
require_once __DIR__ . '/includes/functions.php';

// Verify Security Token
$providedToken = $_GET['token'] ?? '';
if (empty($providedToken) || !hash_equals(CRON_SECURITY_TOKEN, $providedToken)) {
    http_response_code(403);
    echo json_encode(['status' => 'error', 'message' => 'Unauthorized cron access: invalid token.']);
    exit;
}

$today = date('Y-m-d');
$threeDaysFromNow = date('Y-m-d', strtotime('+3 days'));

// 1. Check Leads requiring follow-up today or overdue
$urgentLeads = db_fetch_all("
    SELECT id, contact_person, institution_name, phone, garment_type, follow_up_date 
    FROM leads 
    WHERE status IN ('new', 'contacted', 'quoted') 
      AND follow_up_date IS NOT NULL 
      AND follow_up_date <= ?
    LIMIT 20
", [$today]);

// 2. Check Orders due in 3 days or overdue
$urgentOrders = db_fetch_all("
    SELECT id, order_number, order_title, deadline, status, total_quantity, delivered_quantity 
    FROM orders 
    WHERE status IN ('confirmed', 'in_production') 
      AND deadline IS NOT NULL 
      AND deadline <= ?
    LIMIT 20
", [$threeDaysFromNow]);

// 3. Check Low-Stock Inventory
$lowStock = db_fetch_all("
    SELECT item_name, quantity_on_hand, unit, reorder_threshold 
    FROM inventory 
    WHERE quantity_on_hand <= reorder_threshold
    LIMIT 15
");

// Build summary report
$reportHtml = "
    <div style='font-family: Arial, sans-serif; color: #0f172a; max-width: 650px;'>
        <h2 style='color: #1e3a8a;'>Daily Tailoring Operations Digest (" . date('d M Y') . ")</h2>
        <p>Automated summary generated by your daily cron dispatcher.</p>
";

if (!empty($urgentLeads)) {
    $reportHtml .= "<h3 style='color: #b45309;'>🚨 Follow-Up Reminders (" . count($urgentLeads) . ")</h3><ul>";
    foreach ($urgentLeads as $lead) {
        $name = $lead['institution_name'] ? "{$lead['institution_name']} ({$lead['contact_person']})" : $lead['contact_person'];
        $reportHtml .= "<li><strong>{$name}</strong> — {$lead['garment_type']} (Phone: {$lead['phone']}) - Due: {$lead['follow_up_date']}</li>";
    }
    $reportHtml .= "</ul>";
}

if (!empty($urgentOrders)) {
    $reportHtml .= "<h3 style='color: #dc2626;'>⏱️ Orders Approaching Deadline (" . count($urgentOrders) . ")</h3><ul>";
    foreach ($urgentOrders as $ord) {
        $reportHtml .= "<li><strong>[{$ord['order_number']}] {$ord['order_title']}</strong> — Deadline: {$ord['deadline']} (Delivered: {$ord['delivered_quantity']}/{$ord['total_quantity']})</li>";
    }
    $reportHtml .= "</ul>";
}

if (!empty($lowStock)) {
    $reportHtml .= "<h3 style='color: #d97706;'>📦 Materials Low Stock Alert (" . count($lowStock) . ")</h3><ul>";
    foreach ($lowStock as $item) {
        $reportHtml .= "<li><strong>{$item['item_name']}</strong> — Current: {$item['quantity_on_hand']} {$item['unit']} (Threshold: {$item['reorder_threshold']} {$item['unit']})</li>";
    }
    $reportHtml .= "</ul>";
}

$reportHtml .= "
        <p style='margin-top: 25px;'><a href='" . BASE_URL . "/admin/dashboard.php' style='background: #1e3a8a; color: #fff; padding: 10px 18px; text-decoration: none; border-radius: 6px;'>Open Admin Dashboard</a></p>
    </div>
";

// If any action items exist, send Brevo notification
$notificationsSent = false;
if (!empty($urgentLeads) || !empty($urgentOrders) || !empty($lowStock)) {
    $subject = "Daily Tailor Operations Alert: " . count($urgentLeads) . " Leads, " . count($urgentOrders) . " Orders Due";
    $result = send_brevo_email(BUSINESS_EMAIL, 'Operations Manager', $subject, $reportHtml);
    $notificationsSent = $result['success'] ?? false;
}

echo json_encode([
    'status'             => 'success',
    'timestamp'          => date('Y-m-d H:i:s'),
    'leads_flagged'      => count($urgentLeads),
    'orders_approaching' => count($urgentOrders),
    'low_stock_alerts'   => count($lowStock),
    'notification_sent'  => $notificationsSent
], JSON_PRETTY_PRINT);
